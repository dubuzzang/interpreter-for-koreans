function numbers(text) {
  const out = [];
  const tokens = String(text ?? '').toLowerCase().replace(/ё/g, 'е').match(/[а-я]+|\S/g) || [];
  let run = null;
  const flush = () => { if (run) out.push({ alts: [run.total + run.section], word: true }); run = null; };
  for (let i = 0; i < tokens.length; i++) {
    const w = tokens[i];
    if (w in SCALE && !run && /\d/.test(tokens[i - 1] || '')) continue; // 15 тысяч: 숫자 쪽(decimals)이 센다
    if (w in SCALE) {
      run ??= { total: 0, section: 0, last: 9 };
      run.total += (run.section || 1) * SCALE[w];
      run.section = 0; run.last = 9;
    } else if (w in WORDS) {
      const { v, rank } = WORDS[w];
      if (run && run.section && rank >= run.last) flush(); // два-три · десять двадцать: 따로
      run ??= { total: 0, section: 0, last: 9 };
      run.section += v; run.last = rank;
    } else if (run && w === 'с' && tokens[i + 1] === 'половиной') {
      run.section += 0.5; i++;
    } else flush();
  }
  flush();
  return out;
}

// 숫자로 쓴 큰 수 · 소수 말을 먼저 숫자로: 15 000 ₽ = 15000 (러시아어는 천 단위를 띄어 쓴다) · 15 тыс. = 15000 · 1,5 млн = 1500000 · 3 с половиной = 3.5
const round = (x) => Math.round(x * 1000) / 1000;
const scaleOf = (w) => (/^тыс/i.test(w) ? 1e3 : /^(?:млн|миллион)/i.test(w) ? 1e6 : 1e9);
function decimals(text) {
  return String(text ?? '')
    .replace(/(\d)[   ](?=\d{3}(?!\d))/g, '$1')
    .replace(/(\d+(?:[.,]\d+)?)\s*(тыс(?:яч[а-яё]*)?|млн|миллион[а-яё]*|млрд|миллиард[а-яё]*)\.?/gi, (m, n, w) => String(round(Number(n.replace(',', '.')) * scaleOf(w))))
    .replace(/(\d+(?:[.,]\d+)?)\s+с\s+половиной/gi, (m, n) => String(round(Number(n.replace(',', '.')) + 0.5)));
}

